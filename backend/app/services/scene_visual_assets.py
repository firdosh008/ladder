"""Post-process Excalidraw scenes: AI-generated imagery + optional remote URLs.

Each slide section gets a **context-aware image brief** generated by Claude:
  • whiteboard_sketch  — hand-drawn characters on transparent background
  • screenshot_mockup  — realistic UI/tweet/app window
  • realistic_scene    — photographic, cinematic or colorful scene
  • isometric_diagram  — 3-D flat infographic
  • meme_cultural      — internet meme or pop-culture reference

Placement defaults to **inside each planner frame** aligned to a notional grid
column; set ``SCENE_IMAGE_PLACEMENT=canvas_bottom_strip`` for the legacy strip.
"""

