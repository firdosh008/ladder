def _source_aspect_ratio() -> float:
    """Aspect ratio (w/h) of the generated source images from config."""
    raw = (settings.OPENAI_IMAGE_SIZE or "1024x1024").strip()
    try:
        w_str, h_str = raw.split("x", 1)
        w, h = float(w_str), float(h_str)
        if w > 0 and h > 0:
            return w / h
    except (ValueError, AttributeError):
        pass
    return 1.0


def _mime_from_data_url(data_url: str) -> str:
    head = data_url.split(",", 1)[0].lower()
    if "image/jpeg" in head or "image/jpg" in head:
        return "image/jpeg"
    if "image/webp" in head:
        return "image/webp"
    if "image/gif" in head:
        return "image/gif"
    return "image/png"


def _parse_remote_url_list() -> list[str]:
    raw = (settings.SCENE_REMOTE_IMAGE_URLS or "").strip()
    if not raw:
        return []
    out: list[str] = []
    for part in raw.split(","):
        u = part.strip()
        if u.startswith("https://"):
            out.append(u)
    return out


