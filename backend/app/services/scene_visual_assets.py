_STYLE_DESCRIPTIONS = {
    "whiteboard_sketch": (
        "Clean black-and-white hand-drawn whiteboard sketch / editorial cartoon style. "
        "Bold ink outlines, expressive characters and objects, minimal shading. "
        "TRANSPARENT background — only the drawn elements, no white canvas behind them. "
        "The scene should LITERALLY illustrate the concept with recognizable characters "
        "and props (people, arrows, objects). NO text labels. NO bar charts."
    ),
    "screenshot_mockup": (
        "Hyper-realistic mockup of a UI screenshot, social media post, tweet, app window, "
        "or website — exactly as it would look on a real screen. "
        "Dark or light mode as appropriate to the content. Crisp typography, real-looking "
        "interface chrome (browser bar, like counts, handles). The content inside the "
        "mockup should match the concept described. Landscape composition."
    ),
    "realistic_scene": (
        "Cinematic, photorealistic or richly coloured illustrative scene. "
        "Vibrant colours, dramatic lighting, strong composition. Tells the story "
        "of the concept through people, environments, and objects as if from a "
        "high-quality editorial photo or movie still. Landscape format."
    ),
    "isometric_diagram": (
        "Flat 3-D isometric infographic illustration. Colourful, crisp, modern tech-startup "
        "aesthetic. Shows systems, workflows, or architecture as isometric objects "
        "(servers, people at desks, buildings, pipelines). Clean white background. "
        "Minimal labels — icons and shapes tell the story."
    ),
    "meme_cultural": (
        "Internet meme or pop-culture visual reference that perfectly captures the irony, "
        "humour, or cultural weight of the concept. Could be a well-known meme template "
        "with relevant content, a pop-culture scene parody, or a tongue-in-cheek "
        "illustration. Bold, punchy, immediately recognisable to a tech/internet audience."
    ),
}

_BRIEF_SYSTEM = """\
You are a creative visual director for an educational video platform.
For each slide section you will output a JSON object with:
  "style": one of ["whiteboard_sketch", "screenshot_mockup", "realistic_scene", "isometric_diagram", "meme_cultural"]
  "prompt": a vivid, specific DALL-E image prompt (max 400 chars) tailored to that style
  "transparent_bg": true if style is "whiteboard_sketch" (character floats, no white box), else false

Style selection rules:
- whiteboard_sketch  → concept is a transformation, metaphor, journey, human story, skill, or habit
- screenshot_mockup  → concept references a real product, tweet, website, app, news, social media post
- realistic_scene    → concept involves people in a real-world environment, emotion, or dramatic moment
- isometric_diagram  → concept is a system, architecture, workflow, or technical pipeline
- meme_cultural      → concept is ironic, counter-intuitive, widely-known cultural phenomenon, or has humour

IMPORTANT: Different sections of the SAME video SHOULD use DIFFERENT styles — vary them.
Output ONLY valid JSON array, no markdown fences.
"""


@dataclass
class ImageBrief:
    prompt: str
    transparent_bg: bool = False
    style: str = "whiteboard_sketch"


async def _generate_image_briefs_via_claude(
    idea: IdeaSlice,
    outline: Outline,
    count: int,
) -> list[ImageBrief]:
    """Ask Claude to produce per-section image briefs (style + prompt).

    Falls back to a simple whiteboard-sketch prompt list on any error.
    """
    base = (idea.title or "video").strip()
    items = list(outline.items)[:count]

    sections_txt = "\n".join(
        f"{i+1}. label={it.label!r}  beat={((it.beat or '')[:200])!r}"
        for i, it in enumerate(items)
    )
    # Pad with generic entries if outline has fewer items than count.
    for i in range(len(items), count):
        sections_txt += f"\n{i+1}. label='Section {i+1}'  beat='Key idea from {base}'"

    user_msg = (
        f"Video / lesson title: {base!r}\n\n"
        f"Sections to illustrate ({count} total):\n{sections_txt}\n\n"
        "Return a JSON array with one object per section in order."
    )

    if not settings.ANTHROPIC_API_KEY:
        log.warning("[IMAGE-BRIEF] No ANTHROPIC_API_KEY — using fallback prompts")
        return _fallback_briefs(base, items, count)

    try:
        client = AsyncAnthropic(api_key=settings.ANTHROPIC_API_KEY)
        resp = await client.messages.create(
            model=settings.ANTHROPIC_MODEL,
            max_tokens=1024,
            system=_BRIEF_SYSTEM,
            messages=[{"role": "user", "content": user_msg}],
        )
        raw = resp.content[0].text.strip()
        data = json.loads(raw)
        briefs: list[ImageBrief] = []
        for item in data[:count]:
            style = item.get("style", "whiteboard_sketch")
            style_guide = _STYLE_DESCRIPTIONS.get(style, _STYLE_DESCRIPTIONS["whiteboard_sketch"])
            full_prompt = f"{item.get('prompt', '')} {style_guide}"
            briefs.append(
                ImageBrief(
                    prompt=full_prompt[:3900],
                    transparent_bg=bool(item.get("transparent_bg", False)),
                    style=style,
                )
            )
        while len(briefs) < count:
            briefs.append(_fallback_briefs(base, [], 1)[0])
        log.warning(
            "[IMAGE-BRIEF] Claude produced %d briefs: styles=%s",
            len(briefs),
            [b.style for b in briefs],
        )
        return briefs[:count]
    except Exception as exc:
        log.warning("[IMAGE-BRIEF] Claude brief generation failed: %s — using fallback", exc)
        return _fallback_briefs(base, items, count)


def _fallback_briefs(base: str, items: list, count: int) -> list[ImageBrief]:
    """Simple whiteboard-sketch fallback when Claude is unavailable."""
    briefs: list[ImageBrief] = []
    for it in items:
        beat = (it.beat or "")[:280]
        section = (it.label or "").strip() or "Section"
        prompt = (
            f"Whiteboard sketch: '{section}' from a lesson about '{base}'. "
            f"Hand-drawn characters and objects that depict: {beat}. "
            + _STYLE_DESCRIPTIONS["whiteboard_sketch"]
        )
        briefs.append(ImageBrief(prompt=prompt[:3900], transparent_bg=True, style="whiteboard_sketch"))
    while len(briefs) < count:
        briefs.append(ImageBrief(
            prompt=(
                f"Whiteboard sketch illustrating a key idea from '{base}'. "
                + _STYLE_DESCRIPTIONS["whiteboard_sketch"]
            )[:3900],
            transparent_bg=True,
            style="whiteboard_sketch",
        ))
    return briefs[:count]


def _openai_image_generate_kwargs(prompt: str, *, transparent_bg: bool = False) -> dict:
    """Build ``images.generate`` kwargs per model (quality/size differ by family).

    ``transparent_bg=True`` is honoured only by gpt-image-* models; it is
    silently ignored for dall-e-* which don't support transparency.
    """
    model = (settings.OPENAI_IMAGE_MODEL or "dall-e-3").strip()
    p = prompt[:3900]
    q_raw = (settings.OPENAI_IMAGE_QUALITY or "hd").strip().lower()
    size_override = (settings.OPENAI_IMAGE_SIZE or "").strip()

    if model.startswith("dall-e-3"):
        if size_override in {"1024x1024", "1792x1024", "1024x1792"}:
            size = size_override
        elif settings.SCENE_IMAGE_LANDSCAPE_FOR_DIAGRAMS:
            size = "1792x1024"
        else:
            size = "1024x1024"
        qual = q_raw if q_raw in {"standard", "hd"} else "hd"
        return {
            "model": model,
            "prompt": p,
            "n": 1,
            "size": size,
            "quality": qual,
            "response_format": "b64_json",
        }

    if model.startswith("dall-e-2"):
        return {
            "model": model,
            "prompt": p,
            "n": 1,
            "size": "1024x1024",
            "response_format": "b64_json",
        }

    if model.startswith("gpt-image"):
        if size_override:
            size = size_override
        elif settings.SCENE_IMAGE_LANDSCAPE_FOR_DIAGRAMS:
            size = "1536x1024"
        else:
            size = "1024x1024"
        if q_raw in {"high", "medium", "low", "auto"}:
            qual: str = q_raw
        elif q_raw in {"hd", "best"}:
            qual = "high"
        elif q_raw == "standard":
            qual = "medium"
        elif q_raw == "low":
            qual = "low"
        else:
            qual = "high"
        # GPT Image models return b64_json by default; omit response_format.
        kwargs: dict = {"model": model, "prompt": p, "n": 1, "size": size, "quality": qual}
        if transparent_bg and model == "gpt-image-1":
            # Only gpt-image-1 supports background=transparent; gpt-image-2 does not.
            kwargs["background"] = "transparent"
        return kwargs

    # Unknown model: minimal portable request.
    fallback_kwargs: dict = {
        "model": model,
        "prompt": p,
        "n": 1,
        "size": size_override or "1024x1024",
        "response_format": "b64_json",
    }
    if model.startswith("dall-e"):
        fallback_kwargs["quality"] = q_raw if q_raw in {"standard", "hd"} else "standard"
    return fallback_kwargs


async def _openai_generate_png_urls(briefs: list[ImageBrief]) -> list[str]:
    assert settings.OPENAI_API_KEY
    client = AsyncOpenAI(api_key=settings.OPENAI_API_KEY)
    urls: list[str] = []
    for brief in briefs:
        try:
            kwargs = _openai_image_generate_kwargs(
                brief.prompt, transparent_bg=brief.transparent_bg
            )
            log.warning(
                "[IMAGE-GEN] generating style=%s transparent=%s",
                brief.style,
                kwargs.get("background") == "transparent",
            )
            resp = await client.images.generate(**kwargs)
            row = resp.data[0]
            b64 = getattr(row, "b64_json", None)
            if not b64:
                log.warning("[IMAGE-GEN] no b64_json in response for style=%s", brief.style)
                continue
            urls.append(f"data:image/png;base64,{b64}")
        except Exception as exc:
            exc_str = str(exc)
            # If the model rejected background=transparent, retry without it.
            if "background" in exc_str.lower() and "invalid_value" in exc_str.lower():
                log.warning(
                    "[IMAGE-GEN] model does not support transparent bg, retrying without: %s",
                    exc,
                )
                try:
                    kwargs_no_bg = _openai_image_generate_kwargs(
                        brief.prompt, transparent_bg=False
                    )
                    resp2 = await client.images.generate(**kwargs_no_bg)
                    row2 = resp2.data[0]
                    b64 = getattr(row2, "b64_json", None)
                    if b64:
                        urls.append(f"data:image/png;base64,{b64}")
                    else:
                        log.warning("[IMAGE-GEN] retry also returned no b64_json for style=%s", brief.style)
                except Exception as exc2:
                    log.warning("[IMAGE-GEN] retry also failed for style=%s: %s", brief.style, exc2)
            else:
                log.warning("[IMAGE-GEN] failed for style=%s: %s", brief.style, exc)
    return urls


async def _fetch_remote_image(url: str) -> str | None:
    host = (urlparse(url).hostname or "").lower()
    if host in {"localhost", "127.0.0.1", "::1"} or host.endswith(".localhost"):
        return None
    async with httpx.AsyncClient(timeout=35.0, follow_redirects=True) as client:
        try:
            r = await client.get(url)
        except Exception as e:
            log.warning("remote image fetch failed %s: %s", url, e)
            return None
        if r.status_code != 200:
            return None
        ct = r.headers.get("content-type", "").split(";")[0].strip().lower()
        if ct not in {"image/png", "image/jpeg", "image/webp", "image/gif"}:
            return None
        if len(r.content) > _MAX_REMOTE_BYTES:
            log.warning("remote image too large, skipping: %s", url)
            return None
        b64 = base64.standard_b64encode(r.content).decode("ascii")
        return f"data:{ct};base64,{b64}"


def _max_slots_for_skeleton(skeleton: SceneSkeleton) -> int:
    room = _MAX_SCENE_ELEMENTS - len(skeleton.elements)
    return max(0, min(room, settings.SCENE_AI_IMAGE_COUNT))


def _scatter_rects_in_canvas(
    skeleton: SceneSkeleton,
    n: int,
    *,
    img_side: float = 160.0,
    pad: float = 18.0,
    margin: float = 32.0,
) -> list[tuple[float, float, float, float]]:
    """Up to ``n`` non-overlapping image rects inside existing canvas bounds.

    Builds occupied rects from current elements, scans a coarse grid of
    candidate positions, returns those that don't collide. Used for the MCP
    canvas path where there are no planner frames — images get tucked into
    whatever empty space the diagram left behind.
    """
    cw = float(skeleton.canvas_width)
    ch = float(skeleton.canvas_height)
    step = img_side + 24.0

    occupied: list[tuple[float, float, float, float]] = []
    for el in skeleton.elements:
        ex = float(el.x)
        ey = float(el.y)
        ew = float(el.width or 0)
        eh = float(el.height or 0)
        occupied.append((ex - pad, ey - pad, ex + ew + pad, ey + eh + pad))

    def collides(rx0: float, ry0: float, rx1: float, ry1: float) -> bool:
        for ox0, oy0, ox1, oy1 in occupied:
            if rx0 < ox1 and rx1 > ox0 and ry0 < oy1 and ry1 > oy0:
                return True
        return False

    out: list[tuple[float, float, float, float]] = []
    y = margin
    while y + img_side <= ch - margin and len(out) < n:
        x = margin
        while x + img_side <= cw - margin and len(out) < n:
            if not collides(x, y, x + img_side, y + img_side):
                out.append((x, y, img_side, img_side))
                occupied.append(
                    (x - pad, y - pad, x + img_side + pad, y + img_side + pad)
                )
            x += step
        y += step
    return out


def _embed_scattered_in_canvas(
    skeleton: SceneSkeleton,
    data_urls: list[str],
) -> SceneSkeleton:
    """Place images into empty regions of the existing canvas; overflow → strip."""
    rects = _scatter_rects_in_canvas(skeleton, len(data_urls))
    if not rects:
        return _embed_bottom_strip(skeleton, data_urls)

    placed = data_urls[: len(rects)]
    overflow = data_urls[len(rects) :]

    ts = int(time.time() * 1000)
    files = dict(skeleton.files or {})
    new_elements = list(skeleton.elements)

    for i, (data_url, rect) in enumerate(zip(placed, rects)):
        x, y, img_w, img_h = rect
        fid = f"ladder-hero-{i}-{ts}"
        mime = _mime_from_data_url(data_url)
        files[fid] = {
            "mimeType": mime,
            "id": fid,
            "dataURL": data_url,
            "created": ts,
        }
        new_elements.append(
            SceneSkeletonElement(
                id=f"hero-{i}-{ts}",
                type="image",
                x=x,
                y=y,
                width=img_w,
                height=img_h,
                fileId=fid,
            )
        )

    note_tail = (
        f" Embedded {len(placed)} diagram thumbnails (AI/remote) "
        "scattered into empty canvas regions."
    )
    notes = (skeleton.notes or "") + note_tail
    if len(notes) > 4000:
        notes = notes[:4000]

    sk = skeleton.model_copy(
        update={"elements": new_elements, "files": files, "notes": notes}
    )
    if overflow:
        sk = _embed_bottom_strip(
            sk,
            overflow,
            placement_note=" Additional hero thumbnails along bottom strip.",
        )
    else:
        sk = sort_elements_paint_order(sk)
    return sk


def _frame_anchor_image_rect(frame: SceneFrame, cols: int) -> tuple[float, float, float, float]:
    """Size like one column in an N-column row (e.g. 3 text cells + 1 diagram cell).

    Anchored bottom-right of the frame content area, vertically centered on the
    lower-middle band where slide bodies usually sit.
    """
    pad = 14.0
    inner_w = max(48.0, frame.width - 2 * pad)
    inner_h = max(48.0, frame.height - 2 * pad)
    gutter = 10.0
    ncols = max(3, min(8, cols))
    slot_w = max(88.0, (inner_w - gutter * (ncols - 1)) / float(ncols))
    img_w = slot_w
    img_h = min(max(slot_w * 1.06, 96.0), inner_h * 0.52)

    x = frame.x + frame.width - pad - img_w
    row_anchor_y = frame.y + pad + inner_h * 0.44
    y = row_anchor_y - img_h / 2.0

    x = max(frame.x + pad, min(x, frame.x + frame.width - pad - img_w))
    y = max(frame.y + pad, min(y, frame.y + frame.height - pad - img_h))
    return x, y, img_w, img_h


def _embed_bottom_strip(
    skeleton: SceneSkeleton,
    data_urls: list[str],
    *,
    placement_note: str = " Embedded hero thumbnails (AI/remote) along bottom strip.",
) -> SceneSkeleton:
    cw = float(skeleton.canvas_width)
    ch = float(skeleton.canvas_height)
    n = len(data_urls)
    # Strip layout: slightly larger tiles for diagram previews.
    img_side = min(300.0, max(148.0, cw / float(n + 2)))

    max_bottom = 0.0
    for el in skeleton.elements:
        max_bottom = max(max_bottom, el.y + el.height)

    needed_h = max_bottom + 40.0 + img_side + 36.0
    if needed_h > ch:
        skeleton = skeleton.model_copy(
            update={"canvas_height": min(4800, max(int(ch), int(needed_h)))}
        )
        ch = float(skeleton.canvas_height)

    margin_x = 56.0
    spare_width = cw - 2 * margin_x - n * img_side
    gap = spare_width / max(1.0, float(n - 1)) if n > 1 else 56.0

    base_y = max_bottom + 40.0
    if base_y + img_side > ch - 24.0:
        base_y = ch - img_side - 28.0
    base_y = max(32.0, base_y)

    files = dict(skeleton.files or {})
    new_elements = list(skeleton.elements)
    ts = int(time.time() * 1000)

    for i, data_url in enumerate(data_urls):
        fid = f"ladder-hero-{i}-{ts}"
        x = margin_x + float(i) * (img_side + gap)
        x = min(x, cw - margin_x - img_side)

        mime = _mime_from_data_url(data_url)
        files[fid] = {
            "mimeType": mime,
            "id": fid,
            "dataURL": data_url,
            "created": ts,
        }
        new_elements.append(
            SceneSkeletonElement(
                id=f"hero-{i}-{ts}",
                type="image",
                x=x,
                y=base_y,
                width=img_side,
                height=img_side,
                fileId=fid,
            )
        )

    note_tail = placement_note
    notes = (skeleton.notes or "") + note_tail
    if len(notes) > 4000:
        notes = notes[:4000]

    out = skeleton.model_copy(update={"elements": new_elements, "files": files, "notes": notes})
    # Designer already sorted paint order; appended images must merge into tiers
    # (shapes/images under arrows under text), not stay on top of everything.
    return sort_elements_paint_order(out)


def _embed_visual_images(
    skeleton: SceneSkeleton,
    layout: SceneLayout | None,
    data_urls: list[str],
) -> SceneSkeleton:
    """Place thumbnails inside matching planner frames, or fall back to bottom strip."""
    if settings.SCENE_IMAGE_PLACEMENT == "canvas_bottom_strip":
        return _embed_bottom_strip(skeleton, data_urls)

    frames = list(layout.frames) if layout and layout.frames else []
    if not frames:
        return _embed_scattered_in_canvas(skeleton, data_urls)

    ts = int(time.time() * 1000)
    files = dict(skeleton.files or {})
    new_elements = list(skeleton.elements)
    strip_overflow: list[str] = []

    for i, data_url in enumerate(data_urls):
        if i >= len(frames):
            strip_overflow.append(data_url)
            continue

        f = frames[i]
        x, y, img_w, img_h = _frame_anchor_image_rect(
            f, settings.SCENE_IMAGE_FRAME_GRID_COLUMNS
        )

        fid = f"ladder-hero-{i}-{ts}"
        mime = _mime_from_data_url(data_url)
        files[fid] = {
            "mimeType": mime,
            "id": fid,
            "dataURL": data_url,
            "created": ts,
        }
        new_elements.append(
            SceneSkeletonElement(
                id=f"hero-{i}-{ts}",
                type="image",
                x=x,
                y=y,
                width=img_w,
                height=img_h,
                fileId=fid,
            )
        )

    note_tail = (
        " Embedded diagram thumbnails (AI/remote): grid-column width inside each "
        "outline frame (see SCENE_IMAGE_FRAME_GRID_COLUMNS)."
    )
    notes = (skeleton.notes or "") + note_tail
    if len(notes) > 4000:
        notes = notes[:4000]

    sk = skeleton.model_copy(update={"elements": new_elements, "files": files, "notes": notes})
    if strip_overflow:
        sk = _embed_bottom_strip(
            sk,
            strip_overflow,
            placement_note=" Additional hero thumbnails along bottom strip.",
        )
    else:
        sk = sort_elements_paint_order(sk)
    return sk


async def enrich_scene_visuals(
    skeleton: SceneSkeleton,
    idea: IdeaSlice,
    outline: Outline,
    layout: SceneLayout | None = None,
) -> SceneSkeleton:
    """Attach up to ``SCENE_AI_IMAGE_COUNT`` images without rerunning layout.

    Pipeline:
    1. Claude generates per-section ``ImageBrief`` objects (style + prompt).
    2. OpenAI generates each image with the matched style and transparency flag.
    3. Images are embedded into the skeleton via frame-anchor or scatter layout.
    """
    log.warning(
        "[IMAGE-GEN] enter: elements=%d layout=%s key_set=%s gen_enabled=%s slots_cfg=%d",
        len(skeleton.elements),
        "present" if layout else "None",
        bool(settings.OPENAI_API_KEY),
        settings.SCENE_IMAGE_GEN_ENABLED,
        settings.SCENE_AI_IMAGE_COUNT,
    )
    max_slots = _max_slots_for_skeleton(skeleton)
    if max_slots <= 0:
        log.warning("[IMAGE-GEN] skip: max_slots=0 (canvas full or count=0)")
        return skeleton

    # Step 1: Claude decides the style + writes a tailored prompt per section.
    log.warning("[IMAGE-GEN] generating image briefs via Claude (%d slots)...", max_slots)
    briefs = await _generate_image_briefs_via_claude(idea, outline, max_slots)

    data_urls: list[str] = []

    if settings.OPENAI_API_KEY and settings.SCENE_IMAGE_GEN_ENABLED:
        log.warning(
            "[IMAGE-GEN] calling OpenAI: model=%s n=%d styles=%s",
            settings.OPENAI_IMAGE_MODEL or "dall-e-3",
            max_slots,
            [b.style for b in briefs],
        )
        # Step 2: Generate each image — errors per-image are caught inside.
        data_urls.extend(await _openai_generate_png_urls(briefs))
        log.warning("[IMAGE-GEN] openai returned %d images", len(data_urls))
    else:
        log.warning(
            "[IMAGE-GEN] openai skipped: key=%s enabled=%s",
            bool(settings.OPENAI_API_KEY),
            settings.SCENE_IMAGE_GEN_ENABLED,
        )

    for url in _parse_remote_url_list():
        if len(data_urls) >= max_slots:
            break
        remote = await _fetch_remote_image(url)
        if remote:
            data_urls.append(remote)

    data_urls = data_urls[:max_slots]
    if not data_urls:
        log.warning("[IMAGE-GEN] no data urls produced — returning unenriched skeleton")
        return skeleton

    log.warning(
        "[IMAGE-GEN] embedding %d image(s) via %s",
        len(data_urls),
        "frame_anchor" if layout and layout.frames else "scatter_in_canvas",
    )
    return _embed_visual_images(skeleton, layout, data_urls)
